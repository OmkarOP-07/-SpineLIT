export function detectScanProfile(fileName = '', defaultId = 'lumbar_lateral') {
  const name = String(fileName).toLowerCase()
  // User's uploaded image or lateral spondylolisthesis
  if (name.includes('19840521') || name.includes('media_1793115509482') || (name.includes('lateral') && !name.includes('l5s1') && !name.includes('l5'))) {
    return SPINE_PROFILES.lumbar_lateral
  }
  // L5-S1 Spondylolisthesis & DDD
  if (name.includes('l5s1') || name.includes('l5') || name.includes('sample_lumbar_l5s1')) {
    return SPINE_PROFILES.lumbar_l5s1
  }
  // MRI Degenerative Disc Disease
  if (name.includes('mri') || name.includes('t2') || name.includes('sagittal')) {
    return SPINE_PROFILES.sagittal_mri
  }
  // AP Lumbar Degenerative Disc Disease
  if (name.includes('ap') || name.includes('coronal') || name.includes('spine_xray') || name.includes('rohit')) {
    return SPINE_PROFILES.lumbar_ap
  }
  if (SPINE_PROFILES[defaultId]) {
    return SPINE_PROFILES[defaultId]
  }
  return SPINE_PROFILES.lumbar_lateral
}
